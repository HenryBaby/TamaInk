#include "tamaink_rtc_sleep_gate.h"
#include <cassert>
using namespace tamaink::rtc;
int main() {
  uint8_t r[7] = {0x56, 0x59, 0x23, 0x01, 0x31, 0x12, 0x24};
  DateTime d{};
  uint64_t e = 0;
  assert(decodeDs3231(r, d, e));
  assert(d.year == 2024 && d.hour == 23);
  auto t = encodeTagged(e);
  uint64_t x = 0;
  assert(decodeTagged(t, x) && x == e);
  assert(!decodeTagged(e, x));
  assert(!decodeTagged(t ^ 0x0100000000000000ULL, x));
  uint64_t delta = 0;
  assert(elapsed(e, e + 7, delta) && delta == 7);
  assert(!elapsed(e + 1, e, delta));
  assert(encodeTagged(kMaxEpochSeconds) != 0);
  assert(encodeTagged(kMaxEpochSeconds + 1) == 0);
  assert(!decodeTagged(kTag | (kMaxEpochSeconds + 1), x));
  r[2] = 0x52;
  assert(decodeDs3231(r, d, e) && d.hour == 0);
  r[2] = 0x72;
  assert(decodeDs3231(r, d, e) && d.hour == 12);
  r[0] = 0x6a;
  assert(!decodeDs3231(r, d, e));
  r[0] = 0x00;
  r[3] = 0xf1;
  assert(!decodeDs3231(r, d, e));
  uint8_t leap[7] = {0, 0, 0, 4, 0x29, 0x02, 0x24};
  assert(decodeDs3231(leap, d, e));
  uint8_t bad[7] = {0, 0, 0, 5, 0x29, 0x02, 0x23};
  assert(!decodeDs3231(bad, d, e));
  uint8_t century[7] = {0x59, 0x59, 0x23, 0x05, 0x31, 0x81, 0x00};
  assert(decodeDs3231(century, d, e) && d.year == 2100);
  uint8_t last[7] = {0x59, 0x59, 0x23, 0x05, 0x31, 0x92, 0x99};
  assert(decodeDs3231(last, d, e) && e == kMaxEpochSeconds);
  uint8_t invalid[7] = {0, 0, 0, 1, 1, 1, 0};
  invalid[0] = 0x60;
  assert(!decodeDs3231(invalid, d, e));
  invalid[0] = 0;
  invalid[1] = 0x60;
  assert(!decodeDs3231(invalid, d, e));
  invalid[1] = 0;
  invalid[2] = 0x24;
  assert(!decodeDs3231(invalid, d, e));
  invalid[2] = 0;
  invalid[3] = 0x08;
  assert(!decodeDs3231(invalid, d, e));
  invalid[3] = 1;
  invalid[4] = 0x32;
  assert(!decodeDs3231(invalid, d, e));
  invalid[4] = 1;
  invalid[5] = 0x13;
  assert(!decodeDs3231(invalid, d, e));
  invalid[5] = 1;
  invalid[4] = 0;
  assert(!decodeDs3231(invalid, d, e));
  invalid[4] = 1;
  invalid[3] = 0xf1;
  assert(!decodeDs3231(invalid, d, e));
  return 0;
}
